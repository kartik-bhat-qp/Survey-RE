import assert from 'node:assert/strict';
import test from 'node:test';
import { isCensoredSubthemesEnabled, getDashboardExampleResponses, ensureOutlierTheme, visibleCensoredResponses, isCensoredResponse } from '../src/data/text-ai-censored-subthemes.ts';
import { saveRuntimeTextAiDashboard, getRuntimeTextAiDashboards } from '../src/data/text-ai-dashboard-runtime.ts';

const dashboard = (id, enabled) => ({ id, name: `Creation ${id}`, creationDate: '2026-10-29', commentCount: 7, status: 'Completed', creationPreferences: {
  censoredSubthemesEnabled: enabled, codebookPreference: 'Generated by QuestionPro AI', dashboardLayout: 'Combined dashboard',
  dataSourceName: 'Synthetic source', dataSourceType: 'Surveys', outputLanguage: 'English (en)', questions: [], themeModelingPrompt: 'Identify themes',
} });

test('explicit creation opt-in controls classification, with existing examples preserved', () => {
  assert.equal(isCensoredSubthemesEnabled(dashboard(1, false)), false);
  assert.equal(isCensoredSubthemesEnabled(dashboard(2, true)), true);
  assert.equal(isCensoredSubthemesEnabled({ id: 23 }), true);
  const declined = getDashboardExampleResponses(1, 'q1', {}, false);
  assert.equal(declined.length, 7);
  assert.equal(declined.filter(isCensoredResponse).length, 0);
  assert.equal(visibleCensoredResponses(declined, false).length, 7);
  assert.ok(ensureOutlierTheme([], true, false).every(group => group.subThemes.every(sub => sub.id !== 'censored')));
  const enabled = getDashboardExampleResponses(1, 'q1', {}, true);
  assert.equal(enabled.filter(isCensoredResponse).length, 4);
  assert.equal(visibleCensoredResponses(enabled, false).length, 3);
  assert.equal(visibleCensoredResponses(enabled, true).length, 7);
});

test('the creation choice survives saves and cannot be reversed or removed from existing dashboards', () => {
  const entries = new Map();
  const previousWindow = globalThis.window;
  const previousStorage = globalThis.sessionStorage;
  globalThis.window = {};
  globalThis.sessionStorage = { getItem: key => entries.get(key) ?? null, setItem: (key, value) => entries.set(key, value) };
  try {
    saveRuntimeTextAiDashboard(dashboard(101, true));
    saveRuntimeTextAiDashboard(dashboard(102, false));
    saveRuntimeTextAiDashboard({ ...dashboard(101, false), name: 'Renamed enabled dashboard' });
    saveRuntimeTextAiDashboard(dashboard(102, true));
    let saved = getRuntimeTextAiDashboards();
    assert.equal(isCensoredSubthemesEnabled(saved.find(d => d.id === 101)), true);
    assert.equal(isCensoredSubthemesEnabled(saved.find(d => d.id === 102)), false);
    saveRuntimeTextAiDashboard({ ...dashboard(102, true), creationPreferences: undefined });
    saved = getRuntimeTextAiDashboards();
    assert.equal(isCensoredSubthemesEnabled(saved.find(d => d.id === 102)), false);
    assert.equal(saved.find(d => d.id === 101).name, 'Renamed enabled dashboard');
  } finally {
    if (previousWindow === undefined) delete globalThis.window; else globalThis.window = previousWindow;
    if (previousStorage === undefined) delete globalThis.sessionStorage; else globalThis.sessionStorage = previousStorage;
  }
});
